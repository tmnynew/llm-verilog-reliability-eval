"""Benchmark loading and static validation.

Directory layout (see ``docs/problem_format.md``)::

    benchmark/
      manifest.yaml                 # list of all 30 problems + status
      L1/priority_encoder8/
        meta.json                   # id, title, level, tags, testbench_type, ...
        interface.json              # module name, ports, parameters
        spec_brief.md               # one/two-sentence functional spec
        spec_detailed.md            # port table + cycle-level behaviour, no coding style rules
        golden.v                    # board-verified reference implementation
        tb.v                        # self-checking testbench (TB_RESULT protocol)
        tb_weak.v                   # L2/L3 only: weak testbench for Exp. 2 (mutation score ~60 %)
        escapes/                    # L2/L3 only: LLM samples failing tb.v but passing tb_weak.v
          index.json
          e01.v ...
        mutants/                    # generated by `vleval mutate`
          index.json
          m001.v ...
        equivalent.txt              # ids of mutants confirmed equivalent (excluded from score)
"""

from __future__ import annotations

import json
from collections.abc import Iterable
from pathlib import Path

import yaml

from .models import Interface, Level, Port, Problem, SpecVersion

REQUIRED_FILES = ("meta.json", "interface.json", "spec_brief.md", "spec_detailed.md", "golden.v", "tb.v")

#: Phrases that must NOT appear in functional specs (paper §2.1: specs carry no coding-style constraints).
FORBIDDEN_SPEC_PHRASES = ("非阻塞赋值", "阻塞赋值", "default 分支", "禁用 initial", "nonblocking", "blocking assignment")


class BenchmarkError(RuntimeError):
    pass


def _load_interface(path: Path) -> Interface:
    data = json.loads(path.read_text(encoding="utf-8"))
    ports = [Port(p["name"], p["direction"], int(p.get("width", 1))) for p in data["ports"]]
    return Interface(module=data["module"], ports=ports, parameters={k: int(v) for k, v in data.get("parameters", {}).items()})


def load_problem(root: Path) -> Problem:
    root = Path(root)
    meta = json.loads((root / "meta.json").read_text(encoding="utf-8"))
    iface = _load_interface(root / "interface.json")
    return Problem(
        id=meta["id"],
        level=Level(meta["level"]),
        title=meta["title"],
        interface=iface,
        root=root,
        tags=list(meta.get("tags", [])),
        testbench_type=meta.get("testbench_type", "exhaustive"),
        allowed_latency=int(meta.get("allowed_latency", 0)),
        reference_resources=dict(meta.get("reference_resources", {})),
        clock_port=meta.get("clock_port"),
        status=meta.get("status", "ready"),
    )


class Benchmark:
    """In-memory view of the benchmark directory."""

    def __init__(self, root: Path):
        self.root = Path(root)
        manifest_path = self.root / "manifest.yaml"
        if not manifest_path.exists():
            raise BenchmarkError(f"manifest not found: {manifest_path}")
        self.manifest = yaml.safe_load(manifest_path.read_text(encoding="utf-8")) or {}
        self._problems: dict[str, Problem] = {}
        for entry in self.manifest.get("problems", []):
            pdir = self.root / entry["level"] / entry["id"]
            if entry.get("status", "ready") != "ready":
                continue  # planned problems are listed but not loaded
            if not pdir.exists():
                raise BenchmarkError(f"problem dir missing for ready problem: {pdir}")
            self._problems[entry["id"]] = load_problem(pdir)

    # ----- queries -------------------------------------------------------- #
    def __len__(self) -> int:
        return len(self._problems)

    def __iter__(self) -> Iterable[Problem]:
        return iter(self._problems.values())

    def get(self, pid: str) -> Problem:
        try:
            return self._problems[pid]
        except KeyError as e:
            raise BenchmarkError(f"unknown problem id {pid!r}") from e

    def by_level(self, level: Level) -> list[Problem]:
        return [p for p in self._problems.values() if p.level == level]

    def planned(self) -> list[dict]:
        return [e for e in self.manifest.get("problems", []) if e.get("status") != "ready"]

    # ----- static validation --------------------------------------------- #
    def validate_static(self) -> list[str]:
        """Checks that need no EDA tool. Returns a list of human-readable issues."""
        issues: list[str] = []
        for p in self:
            for f in REQUIRED_FILES:
                if not (p.root / f).exists():
                    issues.append(f"{p.id}: missing {f}")
            for v in SpecVersion:
                try:
                    text = p.spec(v)
                except FileNotFoundError:
                    continue
                for phrase in FORBIDDEN_SPEC_PHRASES:
                    if phrase.lower() in text.lower():
                        issues.append(f"{p.id}: spec_{v.value} contains coding-style constraint {phrase!r}")
            golden = p.golden_path.read_text(encoding="utf-8") if p.golden_path.exists() else ""
            if f"module {p.interface.module}" not in golden:
                issues.append(f"{p.id}: golden.v does not define module {p.interface.module}")
            tb = p.testbench_path.read_text(encoding="utf-8") if p.testbench_path.exists() else ""
            if f"module {p.tb_top}" not in tb:
                issues.append(f"{p.id}: tb.v must define module {p.tb_top}")
            if "TB_RESULT" not in tb:
                issues.append(f"{p.id}: tb.v must print TB_RESULT PASS/FAIL")
            if p.weak_testbench_path.exists():
                weak = p.weak_testbench_path.read_text(encoding="utf-8")
                if f"module {p.tb_top}" not in weak or "TB_RESULT" not in weak:
                    issues.append(f"{p.id}: tb_weak.v must define module {p.tb_top} and print TB_RESULT")
                if p.level == Level.L1:
                    issues.append(f"{p.id}: tb_weak.v is only meant for L2/L3 problems (Exp. 2)")
            if p.level != Level.L1 and not p.clock_port:
                issues.append(f"{p.id}: sequential problem must declare clock_port in meta.json")
        return issues


def find_benchmark_root(start: Path | None = None) -> Path:
    """Locate ``benchmark/`` walking up from *start* (default: this package)."""
    here = Path(start or __file__).resolve()
    for parent in [here, *here.parents]:
        cand = parent / "benchmark"
        if (cand / "manifest.yaml").exists():
            return cand
    raise BenchmarkError("benchmark/manifest.yaml not found")
